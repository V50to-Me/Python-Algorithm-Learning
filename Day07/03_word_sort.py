"""
【题目】单词排序（两次排序 + 稳定性）
给 n 个互不相同的单词，排序规则：
1. 长度长的在前；
2. 长度相同的，字典序大的在前（"zoo" 排在 "apple" 前面）。
每行输出一个单词。

【输入】
第一行：n
接下来 n 行，每行一个单词（只含小写字母）

【示例】
输入：          输出：
5               banana
apple           grape
banana          apple
kiwi            kiwi
fig             fig
grape

【思路】
难点：规则 2 要求字符串按字典序"从大到小"——字符串不能取负号，
负号技巧失效。改用"两次排序 + 稳定性"：

1. 第一次：只按单词排，reverse=True → 字典序降序（次要规则先排）
2. 第二次：按 -len(word) 排 → 长度降序（主要规则后排）

Python 的 sorted 是"稳定"的：key 相同的元素保持原有相对顺序。
第二次排序中长度打平的单词（如 grape 和 apple），
会保持第一次排好的字典序降序顺序——grape 在前。

【核心知识点】
- 稳定排序：key 相同的元素不改变相对顺序
- 两次排序口诀：先次要规则，后主要规则（最后排的说了算）
- 适用场景：某个键是字符串且要降序，负号用不了时

【复杂度】
两次排序，仍是 O(n log n)

【踩坑记录】
- 两次排序的先后顺序不能反：如果先按长度排再按单词排，
  最终结果是"字典序降序，长度打平时保持……什么都不保证"
- 全是数字时不要用两次排序，一次 key=(-a, b) 更简洁；
  两次排序是"字符串要降序"时的专用工具
- 这题不需要元组：列表里直接放单词字符串即可，
  key=len / reverse=True 对字符串本身就能排
"""

n = int(input())
words = []
for _ in range(n):
    words.append(input())

# 第一次：次要规则——字典序降序
ans = sorted(words, reverse=True)
# 第二次：主要规则——长度降序；稳定性保持第一次的相对顺序
ans = sorted(ans, key=lambda w: -len(w))

for word in ans:
    print(word)
