"""
【题目】频次排序（限时综合题：哈希计数 + 排序）
给 n 个整数，统计每个不同整数出现的次数，按以下规则输出去重后的序列：
1. 出现次数多的在前；
2. 次数相同的，数值小的在前。
输出一行，空格分隔。

【输入】
第一行：n（1 <= n <= 10^5）
第二行：n 个整数（绝对值 <= 10^9）

【示例】
输入：                 输出：
8                      3 1 2 5
3 1 3 2 1 3 2 5
（计数：3 出现 3 次，1 和 2 各 2 次，5 出现 1 次；
 次数相同按数值升序，所以 1 在 2 前面）

【思路】
竞赛里极常见的流水线：哈希计数 → items() → 元组列表 → 多关键字排序
1. dict 计数（Day02 的 get 写法）
2. count.items() 天然就是 (数值, 次数) 元组
3. 两个键都是数字 → 取负号一次排序：key 返回 (-次数, 数值)
4. print(*列表) 解包输出，默认空格分隔、不换行

【核心知识点】
- dict 计数：d[x] = d.get(x, 0) + 1
- items() 把计数结果变成可直接排序的 (键, 值) 元组列表
- 全数字多关键字：一次排序 + 负号；有字符串要降序才用两次排序
- print(*lst) 与 " ".join() 两种一行输出方式

【复杂度】
计数 O(n) + 排序 O(k log k)，k 为不同数字个数，总体 O(n log n)

【踩坑记录】
- 次数要降序（取负），数值要升序（不取）——逐位想清楚再写 key
- 输出是一行空格分隔，不是每行一个：print(*lst) 或 print(" ".join(...))
- 两趟排序的写法（先按数值升序，再按次数降序）也对，
  因为两个键都是数字，取负号一次排完更简洁
"""

n = int(input())
nums = list(map(int, input().split()))

count = {}
for x in nums:
    count[x] = count.get(x, 0) + 1

# (数值, 次数) → 次数降序、数值升序
ans = sorted(count.items(), key=lambda t: (-t[1], t[0]))

print(*[value for value, cnt in ans])
