"""
【题目】学生排名（多关键字排序）
n 名学生，每人有名字（不含空格的字符串）和分数（整数）。
排名规则：
1. 分数高的排前面；
2. 分数相同的，按名字字典序从小到大。
输出排序后的名单，每行"名字 分数"。

【输入】
第一行：n
接下来 n 行：名字 分数

【示例】
输入：            输出：
4                 Bob 92
Tom 85            Jerry 92
Jerry 92          Alice 85
Alice 85          Tom 85
Bob 92

【思路】
1. 每行读入后拼成元组 (分数, 名字)，让名字和分数永远绑在一起。
   不能用字典：dict 键必须唯一，两个同名学生会互相覆盖。
2. sorted 的 key 返回 (-分数, 名字)：
   - 元组比较是字典序：先比第 0 位，打平再比第 1 位；
   - 分数取负号：-92 < -85，所以分数大的排前面（降序）；
   - 名字保持原样：字典序升序。
3. 一次 sorted() 同时满足两条规则，不需要手动分组。

【核心知识点】
- 元组：把多个数据捆绑成一个单位
- 元组比较规则（字典序：先比第 0 位，打平再比下一位）
- sorted + key=lambda 自定义排序
- 数字降序技巧：取负号

【复杂度】
排序 O(n log n)；n = 10^5 时 O(n^2) 的选择/冒泡排序必超时

【踩坑记录】
- 字符串数字不能直接比大小："9" > "10"（按字典序逐字符比），
  所以分数读入后必须 int()
- reverse=True 会把整个结果反转，名字也会跟着反——
  不能用它实现"只反转分数"这一个条件
- dict 会丢数据：键必须唯一，同名学生会互相覆盖
"""

n = int(input())
students = []
for _ in range(n):
    name, score = input().split()
    students.append((int(score), name))

result = sorted(students, key=lambda t: (-t[0], t[1]))

for name, score in result:
    print(name, score)
